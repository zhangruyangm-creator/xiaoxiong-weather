    init {
        check(SPRING_FESTIVAL_MD.size == MAX_YEAR - MIN_YEAR + 1)
        check(LUNAR_INFO.size == MAX_YEAR - MIN_YEAR + 1)
    }

    fun isSupported(year: Int): Boolean = year in MIN_YEAR..MAX_YEAR

    /** 农历 [lunarYear] 年闰哪个月（1–12），无闰返回 0。 */
    fun leapMonth(lunarYear: Int): Int {
        if (!isSupported(lunarYear)) return 0
        val m = LUNAR_INFO[lunarYear - MIN_YEAR] and 0xf
        return if (m == 0 || m == 0xf) 0 else m
    }

    fun leapDays(lunarYear: Int): Int {
        if (leapMonth(lunarYear) == 0) return 0
        return if (LUNAR_INFO[lunarYear - MIN_YEAR] and 0x10000 != 0) 30 else 29
    }

    /** 农历非闰月天数。 */
    fun daysInMonth(
        lunarYear: Int,
        month: Int,
    ): Int {
        if (!isSupported(lunarYear) || month !in 1..12) return 0
        return if (LUNAR_INFO[lunarYear - MIN_YEAR] and (0x10000 shr month) == 0) 29 else 30
    }

    /** 公历年 [year] 的春节（农历正月初一）。 */
    fun springFestival(year: Int): LocalDate? {
        if (!isSupported(year)) return null
        val packed = SPRING_FESTIVAL_MD[year - MIN_YEAR]
        return LocalDate.of(year, packed ushr 8, packed and 0xff)
    }

    /**
     * 公历年 [year] 的中秋（农历八月十五）。
     * 由该年春节起，累加正月～七月（含其间闰月）再到十五。
     */
    fun midAutumn(year: Int): LocalDate? {
        val cny = springFestival(year) ?: return null
        val leap = leapMonth(year)
        var offset = 0
        for (m in 1..7) {
            offset += daysInMonth(year, m)
            if (leap == m) offset += leapDays(year)
        }
        offset += 14 // 初一 → 十五
        return cny.plusDays(offset.toLong())
    }
